def _apply_entry(mon: dict, pack: tuple[str, str, list[str], str]) -> None:
    name, blurb, phrases, opening = pack
    emoji = mon.get("emoji") or "👹"
    mon["display_name"] = name
    mon["name"] = f"{emoji} {name}"
    mon["blurb"] = blurb
    mon["phrases"] = phrases
    mon["opening_phrase"] = opening
    mon["victory_phrase"] = f"«{name}» повержен. Трибуна запомнит этот удар."
    mon["defeat_phrase"] = f"«{name}» одерживает верх… на этот раз."


def main() -> None:
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    monsters = data.get("monsters") or {}
    n = 0
    for key, pack in RENAME.items():
        if key not in monsters:
            print(f"skip missing key: {key}")
            continue
        _apply_entry(monsters[key], pack)
        n += 1
    CATALOG.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Updated {n} monsters in {CATALOG}")


if __name__ == "__main__":
    main()
